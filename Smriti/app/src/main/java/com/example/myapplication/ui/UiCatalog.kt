        val freeText = source.startsWith("Story:") || source.startsWith("Patient ID:") || source.startsWith("Import into") || source.startsWith("Enjoys:") || source.startsWith("Avoid:") || source.contains("Emergency") || source.contains("Offline Mode")
        val pattern = buildString {
            var cursor = 0
            for (slot in placeholder.findAll(source)) {
                append(Regex.escape(source.substring(cursor, slot.range.first)))
                val freeSlot = freeText || (source.contains("min overdue") && slot.groupValues[1] == "0") || (source.startsWith("Lvl") && slot.groupValues[1] == "1")
                append(if (freeSlot) "(.*?)" else "([0-9]+(?:[.,][0-9]+)?)")
                cursor = slot.range.last + 1
            }
            append(Regex.escape(source.substring(cursor)))
        }.toRegex()
        Triple(pattern, id, placeholder.findAll(source).map { it.groupValues[1] }.toList())
    }
    fun translate(context: Context, value: String): String {
        labels[value]?.let { return context.getString(it) }
        for ((pattern, id, slots) in templates) {
            val match = pattern.matchEntire(value) ?: continue
            val arguments = slots.mapIndexed { index, slot -> slot to match.groupValues[index + 1] }.toMap()
            return placeholder.replace(context.getString(id)) { arguments[it.groupValues[1]] ?: it.value }
        }
        // Labels may have decorative icons; do not translate arbitrary substrings.
        val core = value.trim().replace(Regex("""^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$"""), "").trim()
        if (core.isNotEmpty()) labels[core]?.let { return value.replace(core, context.getString(it)) }
        return value
    }
}
